import { defineConfig } from 'astro/config';
import react from '@astrojs/react';

// GitHub Pages serves this project from /HabitatBlueprint/. Override both values
// (e.g. SITE_BASE=/ SITE_ORIGIN=https://example.org) when moving to a custom domain.
const base = process.env.SITE_BASE ?? '/HabitatBlueprint';
const site = process.env.SITE_ORIGIN ?? 'https://syncyclic-lab.github.io';

export default defineConfig({
  site,
  base,
  output: 'static',
  trailingSlash: 'ignore',
  build: {
    format: 'directory',
    // External stylesheets keep `style-src` simple; Astro hashes anything it still inlines.
    inlineStylesheets: 'never',
  },
  integrations: [react()],
  // Shiki writes inline styles, which the CSP forbids. No page needs code highlighting.
  markdown: { syntaxHighlight: false },
  devToolbar: { enabled: false },
  security: {
    csp: {
      algorithm: 'SHA-256',
      // script-src and style-src are generated by Astro with hashes for anything inline.
      // frame-ancestors can't be delivered in a <meta> tag; it goes in the header file
      // (dist/_headers) for hosts that support custom headers.
      directives: [
        "default-src 'self'",
        "img-src 'self' data: blob:",
        "font-src 'self'",
        "connect-src 'self'",
        "worker-src 'self' blob:",
        "manifest-src 'self'",
        "media-src 'none'",
        "object-src 'none'",
        "base-uri 'none'",
        "form-action 'none'",
      ],
    },
  },
  vite: {
    build: {
      // Never turn assets into data: URLs; keep every asset a same-origin file.
      assetsInlineLimit: 0,
    },
  },
});
